import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const examplePath = path.join(root, '.env.example');
const localPath = path.join(root, '.env.local');
const developmentLocalPath = path.join(root, '.env.development.local');
const generatedMarker = '# Generated by scripts/prepare-dev-env.mjs';

const publicKeys = [
  'NEXT_PUBLIC_FIREBASE_API_KEY',
  'NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN',
  'NEXT_PUBLIC_FIREBASE_PROJECT_ID',
  'NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET',
  'NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID',
  'NEXT_PUBLIC_FIREBASE_APP_ID',
  'NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID',
  'NEXT_PUBLIC_FIREBASE_VAPID_KEY',
  'NEXT_PUBLIC_CLOUDFLARE_MEDIA_PROXY_URL',
  'NEXT_PUBLIC_ADMIN_EMAIL',
  'NEXT_PUBLIC_GOOGLE_AUTH_ENABLED',
  'NEXT_PUBLIC_SITE_URL',
];

function readEnv(filePath) {
  if (!existsSync(filePath)) return {};
  const values = {};
  for (const rawLine of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const match = /^([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    values[match[1]] = value;
  }
  return values;
}

function isConfigured(value) {
  if (typeof value !== 'string' || !value.trim()) return false;
  const normalized = value.trim().toLowerCase();
  return !(
    normalized.startsWith('replace-with-') ||
    normalized.startsWith('your-') ||
    normalized.startsWith('your_') ||
    /^https?:\/\/your[-_.]/i.test(normalized)
  );
}

function hasFirebaseConfig(values) {
  return [
    'NEXT_PUBLIC_FIREBASE_API_KEY',
    'NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN',
    'NEXT_PUBLIC_FIREBASE_PROJECT_ID',
    'NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET',
    'NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID',
    'NEXT_PUBLIC_FIREBASE_APP_ID',
  ].every((key) => isConfigured(values[key]));
}

const template = readEnv(examplePath);
if (!hasFirebaseConfig(template)) {
  console.warn('[Exam Cracker] .env.example does not contain a complete public Firebase web config; local auth may need manual setup.');
  process.exit(0);
}

const currentDevText = existsSync(developmentLocalPath)
  ? readFileSync(developmentLocalPath, 'utf8')
  : '';
const currentDev = readEnv(developmentLocalPath);
const isGeneratedFile = currentDevText.startsWith(generatedMarker);

// Preserve a complete developer-managed file. Generated files are refreshed
// so edits to .env.local are reflected on the next dev-server start.
if (!isGeneratedFile && hasFirebaseConfig(currentDev)) {
  console.log('[Exam Cracker] Using existing .env.development.local configuration.');
  process.exit(0);
}

const local = readEnv(localPath);
const values = {};
for (const key of publicKeys) {
  const candidates = [
    process.env[key],
    ...(isGeneratedFile ? [] : [currentDev[key]]),
    local[key],
    template[key],
  ];
  values[key] = candidates.find(isConfigured) || '';
}

if (!hasFirebaseConfig(values)) {
  console.warn('[Exam Cracker] Could not prepare local Firebase configuration. Check .env.example or .env.local.');
  process.exit(0);
}

const content = [
  generatedMarker,
  '# Local-only file; edit .env.local for overrides. This file is ignored by Git.',
  ...publicKeys.map((key) => key + '=' + (values[key] || '')),
  '',
].join('\n');

writeFileSync(developmentLocalPath, content, { encoding: 'utf8', mode: 0o600 });
console.log('[Exam Cracker] Prepared local Firebase/public config for the development preview.');
